def normalize_base(value):
    if not re.fullmatch(r"/(?:[A-Za-z0-9_-]+/)*", value):
        raise ValueError("Use an absolute base path with a trailing slash, such as /practical-eval-lab/")
    return value


class Site:
    def __init__(self, output: Path, base_path=DEFAULT_BASE):
        self.output = output.resolve()
        self.base = normalize_base(base_path)
        # Never clean or overwrite a source checkout, a parent, or unrelated files.
        if self.output == ROOT or self.output in ROOT.parents:
            raise ValueError("Build into a dedicated output directory, never the source tree or its parent")
        if self.output.exists() and any(self.output.iterdir()):
            if not (self.output / ".eval-pages-output").is_file():
                raise ValueError("Output directory must be empty or a previous Pages build")
            import shutil
            shutil.rmtree(self.output)
        self.output.mkdir(parents=True, exist_ok=True)
        self.write(".eval-pages-output", "Generated by scripts.build_pages\n")
        self.write(".nojekyll", "")
        self.routes = dict(DOCUMENTS)
        self.routes["docs/incident-case-studies.md"] = "incidents.html"
        self.styles = [self.fingerprint(ROOT / "eval_lab/web" / name, "assets")
                       for name in ("styles.css", "site.css")]
        self.favicon = self.fingerprint(ROOT / "eval_lab/web/favicon.svg", "assets")

    def write(self, name, content):
        target = self.output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            target.write_bytes(content)
        else:
            target.write_text(content, encoding="utf-8")
        return name

    def fingerprint(self, source, directory):
        content = source.read_bytes()
        name = f"{directory}/{source.stem}-{hashlib.sha256(content).hexdigest()[:12]}{source.suffix}"
        return self.write(name, content)

    def url(self, target=""):
        return self.base + target

    def nav(self, current=""):
        if current.startswith("guides/"):
            current = "guides.html"
        links = [("Explore", ""), ("Guides", "guides.html"), ("Incidents", "incidents.html"),
                 ("Architecture", "architecture.html"), ("Get started", "getting-started.html")]
        content = "".join(
            f'<a href="{self.url(target)}"'
            f'{" aria-current=page" if current == target else ""}>{label}</a>'
            for label, target in links)
        return (f'<nav class="nav" aria-label="Main navigation"><a class="brand" href="{self.url()}">'
                '<span class="brand-mark" aria-hidden="true">E</span>Practical Eval Lab</a>'
                f'<div class="site-nav">{content}<a href="{REPO}">GitHub ↗</a></div></nav>')

    def footer(self):
        links = [("Data provenance", "data-provenance.html"), ("Licenses", "notices.html"),
                 ("Security", "security.html"), ("Hosting", "hosting.html")]
        return ('<footer><p>Learn from the result. Keep the evidence.</p>'
                '<p>Original code and synthetic cases: MIT-0. Human-preference sample: Anthropic MIT.</p>'
                '<div class="docs-footer">' + "".join(
                    f'<a href="{self.url(target)}">{label}</a>' for label, target in links)
                + "</div></footer>")

    def head(self, title, description):
        return ('<!doctype html><html lang="en"><head><meta charset="utf-8">'
                '<meta name="viewport" content="width=device-width, initial-scale=1">'
                f'<meta http-equiv="Content-Security-Policy" content="{html.escape(CSP, quote=True)}">'
                f'<title>{html.escape(title)} · Practical Eval Lab</title>'
                f'<meta name="description" content="{html.escape(description, quote=True)}">'
                f'<link rel="icon" href="{self.url(self.favicon)}" type="image/svg+xml">'
                + "".join(f'<link rel="stylesheet" href="{self.url(path)}">' for path in self.styles)
                + "</head><body>")

    def page(self, route, title, description, body, eyebrow="An evaluation workshop"):
        content = (self.head(title, description) + '<a class="skip-link" href="#main">Skip to content</a>'
                   + f'<header class="docs-hero">{self.nav(route)}<div class="hero-copy">'
                   + f'<p class="eyebrow">{html.escape(eyebrow)}</p><h1>{html.escape(title)}</h1>'
                   + f'<p class="hero-description">{html.escape(description)}</p></div></header>'
                   + f'<main id="main" class="page-shell docs-shell">{body}{self.footer()}</main></body></html>\n')
        self.write(route, content)

    def rewrite_link(self, target, source):
        parsed = urlsplit(target)
        if parsed.scheme or parsed.netloc or not parsed.path:
            return target
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), unquote(parsed.path)))
        if path in self.routes:
            destination = self.url(self.routes[path])
        else:
            if path.startswith("../") or not (ROOT / path).exists():
                raise ValueError(f"Broken repository link in {source}: {target}")
            kind = "tree" if (ROOT / path).is_dir() else "blob"
            destination = REPO + f"/{kind}/main/" + quote(path, safe="/")
        return urlunsplit(("", "", destination, parsed.query, parsed.fragment))

    def document(self, source, route):
        text = (ROOT / source).read_text(encoding="utf-8")
        title = text.splitlines()[0].removeprefix("# ").strip()
        site = self

        class Links(Treeprocessor):
            def run(self, root):
                for element in root.iter():
                    attribute = {"a": "href", "img": "src"}.get(element.tag)
                    if attribute and element.get(attribute):
                        element.set(attribute, site.rewrite_link(element.get(attribute), source))
                # Give wide tables their own scroll region rather than the whole page.
                for parent in list(root.iter()):
                    for index, child in enumerate(list(parent)):
                        if child.tag == "table":
                            import xml.etree.ElementTree as ET
                            wrapper = ET.Element("div", {"class": "table-wrap", "tabindex": "0",
                                                         "role": "region", "aria-label": "Scrollable data table"})
                            parent.remove(child)
                            wrapper.append(child)
                            parent.insert(index, wrapper)

        class SiteLinks(Extension):
            def extendMarkdown(self, md):
                md.treeprocessors.register(Links(md), "site_links", 5)

        renderer = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "sane_lists", SiteLinks()])
        body = renderer.convert("\n".join(text.splitlines()[1:]))
        toc = (f'<aside class="docs-toc" aria-label="On this page"><strong>On this page</strong>{renderer.toc}</aside>'
               if renderer.toc_tokens else "")
        for suite, slug in GUIDES.items():
            if source == f"examples/{slug}.md":
                body = (f'<div class="site-links guide-actions"><a class="outline-button" href="{self.url()}?suite={suite}">'
                        'Explore recorded development results →</a>'
                        f'<a class="text-button" href="{self.url()}?suite={suite}&amp;split=holdout">'
                        'Inspect the holdout →</a></div>') + body
        intro = "Read the example, inspect its evidence, then reproduce it in the local lab."
        if source == "README.md":
            intro = "Explore the recorded runs here. Clone the toolkit to run candidates and tune your own evals."
        elif source == "examples/results/README.md":
            intro = "Twelve actual offline comparisons, including holdout failures and regressions."
        self.page(route, title, intro,
                  f'<section class="panel docs-panel"><div class="docs-layout{" no-toc" if not toc else ""}">'
                  f'{toc}'
                  f'<article class="prose">{body}</article></div></section>')

    def downloads(self):
        sources = {
            "LICENSE": "downloads/LICENSE.txt",
            "eval_lab/data/response_quality/LICENSE.txt": "downloads/anthropic-MIT.txt",
            "eval_lab/data/response_quality/provenance.json": "downloads/response-quality-provenance.json",
            "examples/incidents/rag-profile.json": "downloads/incident-rag-profile.json",
            "docs/architecture/pipeline.drawio": "architecture/pipeline.drawio",
            "docs/architecture/pipeline.svg": "architecture/pipeline.svg",
            "docs/images/tuning-lab.png": "assets/tuning-lab.png",
        }
        for source, target in sources.items():
            self.write(target, (ROOT / source).read_bytes())
            self.routes[source] = target

    def recordings(self):
        catalog = {"schema_version": 1, "suites": [], "recordings": {}}
        for suite, meta in CATALOG.items():
            catalog["recordings"][suite] = {}
            counts = {}
            for split in ("dev", "holdout"):
                source = f"examples/results/{suite}-{split}"
                report = validate_report(json.loads((ROOT / f"{source}.json").read_text(encoding="utf-8")))
                if report["after"]["suite"] != suite or report["after"]["split"] != split:
                    raise ValueError(f"Recording does not match its filename: {source}")
                counts[split] = report["after"]["case_count"]
                target = f"reports/{suite}-{split}"
                self.write(f"{target}.json", json.dumps(report, ensure_ascii=False, allow_nan=False) + "\n")
                self.routes[f"{source}.json"] = f"{target}.json"
                self.routes[f"{source}.html"] = f"{target}.html"
                html_files = {}
                for name, value, suffix in (("comparison", report, ""),
                                             ("baseline", report["before"], "-baseline"),
                                             ("improved", report["after"], "-improved")):
                    html_files[name] = self.write(f"{target}{suffix}.html", html_report(value))
                catalog["recordings"][suite][split] = {"json": f"{target}.json", "html": html_files}
            catalog["suites"].append({"id": suite, **{k: v for k, v in meta.items() if k != "prompt"},
                                      "dev_count": counts["dev"], "holdout_count": counts["holdout"]})
        content = json.dumps(catalog, ensure_ascii=False, allow_nan=False) + "\n"
        name = f"samples/catalog-{hashlib.sha256(content.encode()).hexdigest()[:12]}.json"
        return self.write(name, content)

    def explorer(self, catalog):
        source = (ROOT / "eval_lab/web/index.html").read_text(encoding="utf-8")
        app = self.fingerprint(ROOT / "eval_lab/web/app.js", "assets")
        viewer = self.fingerprint(ROOT / "eval_lab/web/public.js", "assets")
        source = source.replace('<html lang="en">', f'<html lang="en" data-mode="public" data-catalog="{catalog}">')
        source = source.replace("<head>", f'<head><meta http-equiv="Content-Security-Policy" content="{html.escape(CSP, quote=True)}">')
        source = source.replace('href="./styles.css"', f'href="{self.url(self.styles[0])}"')
        source = source.replace('href="./favicon.svg"', f'href="{self.url(self.favicon)}"')
        source = source.replace('<script src="./app.js" defer></script>',
                                f'<link rel="stylesheet" href="{self.url(self.styles[1])}">'
                                f'<script src="{self.url(viewer)}" defer></script>'
                                f'<script src="{self.url(app)}" defer></script>')
        source = re.sub(r'<nav class="nav">.*?</nav>', self.nav(), source, count=1)
        source = source.replace("<body>", '<body><a class="skip-link" href="#main">Skip to content</a>')
        source = source.replace("Explore six kinds of evals. Change a case, inspect the grader, and see exactly where a candidate improves—or fails.",
                                "Explore six kinds of evals through recorded experiments. Inspect the grader, compare candidates, and see where a change improves—or fails.")
        source = source.replace("Learn how to evaluate AI behavior. Tune datasets, inspect graders, and compare local baselines.",
                                "Learn AI evaluation with six walkthroughs, recorded experiments, transparent graders, and public incident case studies.")
        source = source.replace("<label>Candidate<select", "<label>Candidate to inspect<select")
        source = source.replace('id="compare" data-lock>Compare candidates', 'id="compare" data-lock>Open recorded comparison')
        source = source.replace('id="run" data-lock>Run selected candidate', 'id="run" data-lock>View candidate results')
        source = source.replace("Development · editable", "Development · recorded").replace("Holdout · bundled cases", "Holdout · recorded")
        source = source.replace("Loading the local lab…", "Loading recorded experiments…")
        notice = ('<section class="public-notice" aria-labelledby="viewer-heading">'
                  '<h2 id="viewer-heading">Explore evidence. Then try your own eval.</h2>'
                  '<p>This viewer opens actual recorded runs of the bundled local rules. '
                  'Five suites use synthetic examples; response quality uses a small attributed human-preference sample. '
                  'These are teaching results, not model benchmarks.</p>'
                  f'<p><a href="{self.url("guides.html")}">Read the six walkthroughs →</a> · '
                  f'<a href="{self.url("getting-started.html")}">Run and tune the lab locally →</a></p></section>')
        source = source.replace('<main class="page-shell">', '<main id="main" class="page-shell">' + notice)
        source = re.sub(r"<footer>.*?</footer>", self.footer(), source, flags=re.S)
        self.write("index.html", source)

    def guides(self):
        cards = []
        for index, (suite, slug) in enumerate(GUIDES.items(), 1):
            meta = CATALOG[suite]
            cards.append('<article class="panel lesson-card">'
                         f'<p class="lesson-number">EXAMPLE {index:02}</p><h2>{html.escape(meta["title"])}</h2>'
                         f'<p>{html.escape(meta["lesson"])}</p><div class="site-links">'
                         f'<a class="outline-button" href="{self.url(f"guides/{slug}.html")}">Read walkthrough →</a>'
                         f'<a class="text-button" href="{self.url()}?suite={suite}">Explore results →</a>'
                         '</div></article>')
        body = ('<section class="panel docs-panel prose"><h2>Follow the whole evaluation loop.</h2>'
                '<p>Define success, choose cases, inspect a grader, compare a change, and check the holdout. '
                'Each walkthrough explains a failure you can reproduce and what its score cannot establish.</p>'
                f'<div class="site-links"><a class="outline-button" href="{self.url("learning-guide.html")}">Start with eval fundamentals</a>'
                f'<a class="outline-button" href="{self.url("integrations.html")}">Connect your application</a>'
                f'<a class="outline-button" href="{self.url("results.html")}">All recorded experiments</a></div></section>'
                + '<section class="lesson-cards" aria-label="Six eval walkthroughs">' + "".join(cards) + "</section>")
        self.page("guides.html", "Six ways to ask: does it work?",
                  "Small datasets. Transparent graders. Changes that sometimes make things worse.", body)

    def architecture(self):
        body = ('<section class="panel docs-panel prose"><h2>The local evaluation loop</h2>'
                '<p>The Python runner keeps reference answers with the grader and passes only inputs to a candidate. '
                'Matched reports show what changed. Local tuning profiles and saved experiments stay on your computer.</p>'
                f'<img class="architecture-image" src="{self.url("architecture/pipeline.svg")}" '
                'alt="Dataset inputs go to a candidate. Reference answers go directly to the grader. Reports and tuning profiles complete the loop.">'
                '<div class="site-links">'
                f'<a class="outline-button" href="{self.url("architecture/pipeline.drawio")}" download>Download editable diagram</a>'
                f'<a class="text-button" href="{self.url("architecture/pipeline.svg")}">Open full-size SVG</a></div>'
                '<h2>What runs on this website?</h2><p>GitHub Pages serves documentation and recorded JSON/HTML reports. '
                'The explorer loads those static files and renders the same result components as the local lab. '
                'To execute candidates, edit cases, or save experiments, start the Python lab locally.</p>'
                '<p>The hosted viewer has no execution backend, model credentials, browser storage, analytics, '
                'or cloud integrations. AWS services are not part of this architecture.</p>'
                f'<p><a href="{self.url("contracts.html")}">Read the data contracts</a> · '
                f'<a href="{self.url("hosting.html")}">How the site is built and deployed</a></p></section>')
        self.page("architecture.html", "Follow the evidence.",
                  "See how datasets, candidates, graders, and reports fit together.", body)

    def incidents(self):
        content = (ROOT / "eval_lab/web/incidents.html").read_text(encoding="utf-8")
        content = content.replace("<head>", f'<head><meta http-equiv="Content-Security-Policy" content="{html.escape(CSP, quote=True)}">')
        content = content.replace('href="./styles.css"', f'href="{self.url(self.styles[0])}"')
        content = content.replace("</head>", f'<link rel="stylesheet" href="{self.url(self.styles[1])}"></head>')
        content = content.replace('href="./favicon.svg"', f'href="{self.url(self.favicon)}"')
        content = re.sub(r'<nav class="nav">.*?</nav>', self.nav("incidents.html"), content, count=1)
        content = content.replace("<body>", '<body><a class="skip-link" href="#main">Skip to content</a>')
        content = content.replace('<main class="page-shell', '<main id="main" class="page-shell')
        content = content.replace("Open related eval →", "Explore related recording →")
        content = re.sub(r"<footer>.*?</footer>", self.footer(), content, flags=re.S)
        self.write("incidents.html", content)

    def build(self):
        self.downloads()
        catalog = self.recordings()
        self.explorer(catalog)
        self.guides()
        self.architecture()
        self.incidents()
        for source, target in DOCUMENTS.items():
            self.document(source, target)
        self.page("404.html", "That page is missing.",
                  "Choose a walkthrough or return to the recorded-results explorer.",
                  f'<section class="panel docs-panel"><a class="primary-button" href="{self.url()}">Open the explorer</a></section>')
        # This public inventory contains only relative paths and file digests.
        files = {p.relative_to(self.output).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
                 for p in sorted(self.output.rglob("*")) if p.is_file() and not p.name.startswith(".")}
        self.write("site-manifest.json", json.dumps({"schema_version": 1, "base_path": self.base,
                                                   "mode": "recorded-results", "files": files}, indent=2) + "\n")
        return self.output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("site"))
    parser.add_argument("--base-path", default=DEFAULT_BASE)
    args = parser.parse_args()
    output = Site(args.output, args.base_path).build()
    print(f"Built GitHub Pages site: {output} ({len(list(output.rglob('*.html')))} HTML pages)")


if __name__ == "__main__":
    main()
