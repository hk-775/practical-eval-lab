    def write_markdown(self, route, text, source):
        digest = hashlib.sha256((ROOT / source).read_bytes()).hexdigest()
        source_url = REPO + "/blob/main/" + source
        content = (text.rstrip() + f"\n\n---\nSource: [{source}]({source_url})\n\n"
                   f"Source SHA-256: `{digest}`\n")
        self.write(route, content)
        self.markdown_records[route] = {
            "source": source, "source_url": source_url, "source_sha256": digest,
            "markdown_url": self.absolute(route),
            "sha256": hashlib.sha256(content.encode("utf-8")).hexdigest(),
            "bytes": len(content.encode("utf-8")),
        }

    def markdown_document(self, source, route):
        text = (ROOT / source).read_text(encoding="utf-8")
        mirrors = {self.url(target): self.url(target.removesuffix(".html") + ".md")
                   for target in DOCUMENTS.values()}
        mirrors[self.url("incidents.html")] = self.url("incidents.md")

        def link(match):
            target = self.rewrite_link(match[2], source)
            parsed = urlsplit(target)
            if not parsed.scheme and not parsed.netloc and parsed.path.startswith(self.base):
                path = mirrors.get(parsed.path, parsed.path)
                target = urlunsplit(("https", "hk-775.github.io", path, parsed.query, parsed.fragment))
            return match[1] + target + match[3]

        lines, fence = [], None
        for line in text.splitlines():
            marker = re.match(r"\s*(`{3,}|~{3,})", line)
            if marker:
                if fence is None:
                    fence = marker[1]
                elif marker[1][0] == fence[0] and len(marker[1]) >= len(fence) and not line[marker.end():].strip():
                    fence = None
                lines.append(line)
            else:
                lines.append(line if fence else re.sub(r"(!?\[[^\]]*\]\()([^\s)]+)(\))", link, line))
        self.write_markdown(route, "\n".join(lines), source)

    def rewrite_link(self, target, source):
        parsed = urlsplit(target)
        if parsed.scheme or parsed.netloc or not parsed.path:
            return target
        path = posixpath.normpath(posixpath.join(posixpath.dirname(source), unquote(parsed.path)))
        if path in self.routes:
            destination = self.url(self.routes[path])
        else:
            if path.startswith("../") or not (ROOT / path).exists():
                raise ValueError(f"Broken repository link in {source}: {target}")
            kind = "tree" if (ROOT / path).is_dir() else "blob"
            destination = REPO + f"/{kind}/main/" + quote(path, safe="/")
        return urlunsplit(("", "", destination, parsed.query, parsed.fragment))

    def document(self, source, route):
        self.markdown_document(source, route.removesuffix(".html") + ".md")
        text = (ROOT / source).read_text(encoding="utf-8")
        title = text.splitlines()[0].removeprefix("# ").strip()
        site = self

        class Links(Treeprocessor):
            def run(self, root):
                for element in root.iter():
                    attribute = {"a": "href", "img": "src"}.get(element.tag)
                    if attribute and element.get(attribute):
                        element.set(attribute, site.rewrite_link(element.get(attribute), source))
                # Give wide tables their own scroll region rather than the whole page.
                for parent in list(root.iter()):
                    for index, child in enumerate(list(parent)):
                        if child.tag == "table":
                            import xml.etree.ElementTree as ET
                            wrapper = ET.Element("div", {"class": "table-wrap", "tabindex": "0",
                                                         "role": "region", "aria-label": "Scrollable data table"})
                            parent.remove(child)
                            wrapper.append(child)
                            parent.insert(index, wrapper)

        class SiteLinks(Extension):
            def extendMarkdown(self, md):
                md.treeprocessors.register(Links(md), "site_links", 5)

        renderer = markdown.Markdown(extensions=["fenced_code", "tables", "toc", "sane_lists", SiteLinks()])
        body = renderer.convert("\n".join(text.splitlines()[1:]))
        toc = (f'<aside class="docs-toc" aria-label="On this page"><strong>On this page</strong>{renderer.toc}</aside>'
               if renderer.toc_tokens else "")
        for suite, slug in GUIDES.items():
            if source == f"examples/{slug}.md":
                body = (f'<div class="site-links guide-actions"><a class="outline-button" href="{self.url()}?suite={suite}">'
                        'Explore recorded development results →</a>'
                        f'<a class="text-button" href="{self.url()}?suite={suite}&amp;split=holdout">'
                        'Inspect the holdout →</a></div>') + body
        intro = "Read the example, inspect its evidence, then reproduce it in the local lab."
        if source == "README.md":
            intro = "Explore the recorded runs here. Clone the toolkit to run candidates and tune your own evals."
        elif source == "examples/results/README.md":
            intro = "Twelve actual offline comparisons, including holdout failures and regressions."
        elif source == "benchmarks/decision_models/README.md":
            intro = "An exploratory fixture with documented design limitations. Inspect the inputs, failures, and scope of the evidence."
        elif source == "benchmarks/decision_models/recordings/README.md":
            intro = "Local Mac measurements on a small diagnostic fixture. These scores do not establish a model ranking."
        elif source == "benchmarks/decision_models/DESIGN_REVIEW.md":
            intro = "What the initial fixture can establish, where its design falls short, and how to build a deployment-oriented evaluation."
        elif source == "benchmarks/tool_workflow/README.md":
            intro = "An executable support simulation: tool choice, arguments, clarification, authorization, fallback, and measured outcomes."
        self.page(route, title, intro,
                  f'<section class="panel docs-panel"><div class="docs-layout{" no-toc" if not toc else ""}">'
                  f'{toc}'
                  f'<article class="prose">{body}</article></div></section>')

