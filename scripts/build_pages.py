def normalize_base(value):
    if not re.fullmatch(r"/(?:[A-Za-z0-9_-]+/)*", value):
        raise ValueError("Use an absolute base path with a trailing slash, such as /practical-eval-lab/")
    return value


class Site:
    def __init__(self, output: Path, base_path=DEFAULT_BASE):
        self.output = output.resolve()
        self.base = normalize_base(base_path)
        # Never clean or overwrite a source checkout, a parent, or unrelated files.
        if self.output == ROOT or self.output in ROOT.parents:
            raise ValueError("Build into a dedicated output directory, never the source tree or its parent")
        if self.output.exists() and any(self.output.iterdir()):
            if not (self.output / ".eval-pages-output").is_file():
                raise ValueError("Output directory must be empty or a previous Pages build")
            import shutil
            shutil.rmtree(self.output)
        self.output.mkdir(parents=True, exist_ok=True)
        self.write(".eval-pages-output", "Generated by scripts.build_pages\n")
        self.write(".nojekyll", "")
        self.routes = dict(DOCUMENTS)
        self.routes["docs/incident-case-studies.md"] = "incidents.html"
        self.routes["AGENTS.md"] = "coding-agents.md"
        self.pages = {}
        self.markdown_records = {}
        self.styles = [self.fingerprint(ROOT / "eval_lab/web" / name, "assets")
                       for name in ("styles.css", "site.css")]
        self.favicon = self.fingerprint(ROOT / "eval_lab/web/favicon.svg", "assets")

    def write(self, name, content):
        target = self.output / name
        target.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(content, bytes):
            target.write_bytes(content)
        else:
            target.write_bytes(content.encode("utf-8"))
        return name

    def fingerprint(self, source, directory):
        content = source.read_bytes()
        name = f"{directory}/{source.stem}-{hashlib.sha256(content).hexdigest()[:12]}{source.suffix}"
        return self.write(name, content)

    def url(self, target=""):
        return self.base + target

    def absolute(self, target=""):
        return ORIGIN + self.url(target)

