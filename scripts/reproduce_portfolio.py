"""Generate actual offline comparisons and a compact index. No model calls."""

import argparse
import json
from pathlib import Path

from eval_lab.core import compare_reports, run_eval
from eval_lab.reports import html_report
from eval_lab.suites import CATALOG


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("reports/portfolio"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    rows = []
    for suite in CATALOG:
        for split in ("dev", "holdout"):
            before = run_eval(suite, "baseline", split)
            after = run_eval(suite, "improved", split)
            report = compare_reports(before, after)
            if before["execution_errors"] or after["execution_errors"]:
                raise RuntimeError(f"Unexpected execution failure in {suite}/{split}")
            name = f"{suite}-{split}"
            (args.output / f"{name}.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
            (args.output / f"{name}.html").write_text(html_report(report), encoding="utf-8")
            rows.append(f"| {suite} | {split} | {before['passed']}/{before['total']} | {after['passed']}/{after['total']} | {report['regressed']} | [JSON]({name}.json) · [HTML]({name}.html) |")
    text = """# Recorded offline experiments

Generated by `python -m scripts.reproduce_portfolio`. These are actual runs of local rules,
not model performance claims. No API calls were made. Timing depends on the machine.
Download an HTML file and open it locally, or import JSON through the webpage.
Reproduce into an ignored directory with `uv run --locked python -m scripts.reproduce_portfolio`.
The source and grader fingerprints change when implementation changes; recorded reports
are comparable with each other, but may require rerunning to compare with a later checkout.

| Suite | Split | Baseline passes | Improved passes | Regressions | Evidence |
|---|---|---:|---:|---:|---|
"""
    (args.output / "README.md").write_text(text + "\n".join(rows) + "\n", encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
